// 并入 WAITE_LORE：顶层 symCN/upCN/revCN 直接赋值；love/work/advice 合并其 upCN/revCN。
(function mergeWaiteCN() {
  if (typeof WAITE_LORE === 'undefined') return;
  for (const id in WAITE_LORE_CN) {
    const src = WAITE_LORE_CN[id], dst = WAITE_LORE[id];
    if (!dst) continue;
    for (const k in src) {
      if (k === 'love' || k === 'work' || k === 'advice') {
        dst[k] = dst[k] || {};
        Object.assign(dst[k], src[k]);
      } else {
        dst[k] = src[k];
      }
    }
  }
})();
